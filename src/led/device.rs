/*!
    WS2812 output device. The strip timing is generated by the Pi's SPI
    hardware (MOSI = GPIO 10, pin 19): each WS2812 bit is encoded as four
    SPI bits at 4x800 kHz, so no userspace real-time tricks are needed.
*/

use anyhow::Result;

/// Byte order the strip expects on the wire, e.g. `brg` (the order the
/// Arduino firmware used). `wire[k]` is the index into (r, g, b) of the
/// k-th transmitted color byte.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ColorOrder {
    wire: [usize; 3],
}

impl ColorOrder {
    pub fn parse(s: &str) -> Option<Self> {
        let lower = s.trim().to_ascii_lowercase();
        let bytes = lower.as_bytes();
        if bytes.len() != 3 {
            return None;
        }
        let idx = |c: u8| match c {
            b'r' => Some(0),
            b'g' => Some(1),
            b'b' => Some(2),
            _ => None,
        };
        let first = idx(bytes[0])?;
        let second = idx(bytes[1])?;
        let third = idx(bytes[2])?;
        // A permutation of r/g/b, no repeats.
        if first == second || second == third || first == third {
            return None;
        }
        Some(ColorOrder {
            wire: [first, second, third],
        })
    }

    // Consumed by the Linux SPI path and the tests.
    #[cfg_attr(not(any(test, target_os = "linux")), allow(dead_code))]
    pub fn wire_bytes(&self, rgb: [u8; 3]) -> [u8; 3] {
        [rgb[self.wire[0]], rgb[self.wire[1]], rgb[self.wire[2]]]
    }
}

impl Default for ColorOrder {
    fn default() -> Self {
        ColorOrder { wire: [2, 0, 1] } // brg — order the strip was driven with
    }
}

pub trait LedDevice: Send {
    /// Pushes one frame of brightness-scaled (r, g, b) pixels to the strip.
    fn render(&mut self, pixels: &[[u8; 3]]) -> Result<()>;

    /// Downcast support for tests.
    #[cfg_attr(not(test), allow(dead_code))]
    fn as_any(&self) -> &dyn std::any::Any;
}

/// No-op device for non-Linux hosts and tests; records the last frame.
pub struct NullDevice {
    pub last_frame: Vec<[u8; 3]>,
    pub frames: usize,
}

impl NullDevice {
    // Test/no-op path only; unused in a Linux release build.
    #[cfg_attr(all(not(test), target_os = "linux"), allow(dead_code))]
    pub fn new() -> Self {
        NullDevice {
            last_frame: Vec::new(),
            frames: 0,
        }
    }
}

impl LedDevice for NullDevice {
    fn render(&mut self, pixels: &[[u8; 3]]) -> Result<()> {
        self.last_frame = pixels.to_vec();
        self.frames += 1;
        Ok(())
    }

    fn as_any(&self) -> &dyn std::any::Any {
        self
    }
}

/// SPI bit encoding: a WS2812 bit period (1.25 us) is four SPI bits at
/// 3.2 MHz. Logic 0 = 1000 (312 ns high), logic 1 = 1110 (937 ns high).
#[cfg_attr(not(any(test, target_os = "linux")), allow(dead_code))]
pub fn encode_byte(b: u8) -> [u8; 4] {
    let mut out = [0u8; 4];
    for bit in 0..8 {
        let nibble: u8 = if b & (0x80 >> bit) != 0 {
            0b1110
        } else {
            0b1000
        };
        if bit % 2 == 0 {
            out[bit / 2] |= nibble << 4;
        } else {
            out[bit / 2] |= nibble;
        }
    }
    out
}

/// >50 us of line-low time after the frame so the pixels latch.
#[cfg_attr(not(target_os = "linux"), allow(dead_code))]
const LATCH_BYTES: usize = 24;

#[cfg(target_os = "linux")]
pub struct SpiWs2812 {
    dev: spidev::Spidev,
    order: ColorOrder,
    buf: Vec<u8>,
}

#[cfg(target_os = "linux")]
impl SpiWs2812 {
    pub fn open(path: &str, speed_hz: u32, order: ColorOrder, led_count: usize) -> Result<Self> {
        use spidev::{SpiModeFlags, Spidev, SpidevOptions};

        let mut dev = Spidev::open(path)?;
        let mut options = SpidevOptions::new();
        options
            .bits_per_word(8)
            .max_speed_hz(speed_hz)
            .mode(SpiModeFlags::SPI_MODE_0);
        dev.configure(&options)?;
        check_spidev_bufsiz(frame_len(led_count))?;
        Ok(SpiWs2812 {
            dev,
            order,
            buf: Vec::with_capacity(frame_len(led_count)),
        })
    }
}

/// Total SPI bytes pushed per frame: 12 encoded bytes per LED + latch.
#[cfg(target_os = "linux")]
fn frame_len(led_count: usize) -> usize {
    led_count * 12 + LATCH_BYTES
}

#[cfg(target_os = "linux")]
fn check_spidev_bufsiz(frame_bytes: usize) -> Result<()> {
    let bufsiz = match std::fs::read_to_string("/sys/module/spidev/parameters/bufsiz") {
        Ok(s) => s.trim().parse::<usize>().unwrap_or(0),
        Err(_) => return Ok(()), // unreadable: can't tell, let writes speak
    };
    if frame_bytes > bufsiz {
        Err(anyhow::anyhow!(
            "the SPI frame ({frame_bytes} bytes) does not fit the spidev transfer \
             buffer ({bufsiz} bytes) — every write would fail with 'Message too long'. \
             Enlarge it to e.g. 32768 and reboot: if spidev is built in, append \
             'spidev.bufsiz=32768' to the kernel command line in \
             /boot/firmware/cmdline.txt (or /boot/cmdline.txt on older releases); \
             if it is a module (listed in /proc/modules), create \
             /etc/modprobe.d/spidev.conf with 'options spidev bufsiz=32768'"
        ))
    } else {
        Ok(())
    }
}

#[cfg(target_os = "linux")]
impl LedDevice for SpiWs2812 {
    fn render(&mut self, pixels: &[[u8; 3]]) -> Result<()> {
        use std::io::Write;

        self.buf.clear();
        for px in pixels {
            for byte in self.order.wire_bytes(*px) {
                self.buf.extend_from_slice(&encode_byte(byte));
            }
        }
        self.buf.resize(self.buf.len() + LATCH_BYTES, 0);
        if let Err(e) = self.dev.write_all(&self.buf) {
            if e.raw_os_error() == Some(90) {
                return Err(anyhow::anyhow!(
                    "frame ({} bytes) exceeds the spidev transfer buffer \
                     (spidev.bufsiz) — see the README section on large strips",
                    self.buf.len()
                ));
            }
            return Err(e.into());
        }
        Ok(())
    }

    fn as_any(&self) -> &dyn std::any::Any {
        self
    }
}

pub fn open(
    path: &str,
    speed_hz: u32,
    order: ColorOrder,
    led_count: usize,
) -> Result<Box<dyn LedDevice>> {
    #[cfg(target_os = "linux")]
    {
        let device = SpiWs2812::open(path, speed_hz, order, led_count)?;
        println!(
            "[LED] SPI output on {path}: {} LEDs, color order ok",
            led_count
        );
        Ok(Box::new(device))
    }
    #[cfg(not(target_os = "linux"))]
    {
        let _ = (path, speed_hz, order, led_count);
        eprintln!("[LED] not Linux: LED output disabled (NullDevice)");
        Ok(Box::new(NullDevice::new()))
    }
}

#[cfg(test)]
mod tests {
    use super::{ColorOrder, LedDevice, NullDevice, encode_byte};

    #[test]
    fn encodes_spi_nibbles() {
        assert_eq!(encode_byte(0x00), [0x88, 0x88, 0x88, 0x88]);
        assert_eq!(encode_byte(0xFF), [0xEE, 0xEE, 0xEE, 0xEE]);
        // Only the LSB set: last nibble is a one-bit.
        assert_eq!(encode_byte(0x01), [0x88, 0x88, 0x88, 0x8E]);
        // Only the MSB set: first nibble is a one-bit.
        assert_eq!(encode_byte(0x80), [0xE8, 0x88, 0x88, 0x88]);
        assert_eq!(encode_byte(0b1010_0001), [0xE8, 0xE8, 0x88, 0x8E]);
    }

    #[test]
    fn color_order_permutes_wire_bytes() {
        let brg = ColorOrder::parse("brg").unwrap();
        assert_eq!(brg.wire_bytes([10, 20, 30]), [30, 10, 20]); // b, r, g
        let grb = ColorOrder::parse("GRB").unwrap();
        assert_eq!(grb.wire_bytes([10, 20, 30]), [20, 10, 30]);
        assert_eq!(ColorOrder::default().wire_bytes([10, 20, 30]), [30, 10, 20]);
    }

    #[test]
    fn color_order_rejects_junk() {
        assert!(ColorOrder::parse("rgbx").is_none());
        assert!(ColorOrder::parse("rg b").is_none());
        assert!(ColorOrder::parse("rrg").is_none());
        assert!(ColorOrder::parse("rg").is_none());
        assert!(ColorOrder::parse("rgba").is_none());
        assert!(ColorOrder::parse("xyz").is_none());
    }

    #[test]
    fn null_device_records_frames() {
        let mut dev = NullDevice::new();
        dev.render(&[[1, 2, 3], [4, 5, 6]]).unwrap();
        assert_eq!(dev.last_frame, vec![[1, 2, 3], [4, 5, 6]]);
        assert_eq!(dev.frames, 1);
    }
}
